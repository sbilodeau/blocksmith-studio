#!/usr/bin/env node
/**
 * Regenerates resources/data/migrations.json: how texture paths change between consecutive Minecraft versions of
 * the version table, from 1.21.4 (start of the support window) to the newest entry (see docs/versions.md).
 *
 *   node scripts/gen-migrations.mjs            # fetch the file lists, write the table
 *   node scripts/gen-migrations.mjs --dry-run  # print a summary instead of writing
 *
 * Source: the per-version asset trees of https://github.com/misode/mcmeta (tags "<version>-assets"), read through
 * the GitHub API: every file path with its git blob hash (a content hash). Only paths and hashes are read; no game
 * file is downloaded or stored. Set GITHUB_TOKEN (or GH_TOKEN) to raise the API rate limit.
 * Cross-check: when a version's client jar is in the local launcher folder, the hash of one of its textures is
 * compared with the tree's (the script stops if they differ).
 *
 * For each pair (older -> newer):
 * - renamed: a texture only in the older version and one only in the newer version with the same content hash;
 * - added: textures only in the newer version (skipped when exporting down to the older one);
 * - removed: textures only in the older version (skipped when importing / upgrading to the newer one).
 * Renames whose content also changed cannot be detected: add them to "manual" (kept across regenerations).
 */
import { createHash } from 'node:crypto'
import { existsSync, readFileSync } from 'node:fs'
import { writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { unzipSync } from 'fflate'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = join(root, 'resources', 'data', 'migrations.json')
const VERSIONS = join(root, 'resources', 'data', 'versions.json')

/** First version of the migration chain. */
export const FIRST_VERSION = '1.21.4'

const TEXTURE = /^assets\/minecraft\/textures\/.+\.png$/

/**
 * Builds the migration table from asset trees.
 * @param {Array<{ id: string, files: Map<string, string> }>} trees oldest first: texture path -> content hash
 * @param {Array<{ from: string, to: string, older: string, newer: string }>} manual hand-reviewed renames
 * @param {string} generatedAt YYYY-MM-DD
 */
export function buildMigrations(trees, manual, generatedAt) {
  const transitions = []
  for (let i = 1; i < trees.length; i++) {
    const older = trees[i - 1]
    const newer = trees[i]
    const onlyOlder = [...older.files.keys()].filter((p) => !newer.files.has(p))
    const onlyNewer = [...newer.files.keys()].filter((p) => !older.files.has(p))
    const byHash = new Map()
    for (const p of onlyOlder) {
      const h = older.files.get(p)
      byHash.set(h, byHash.has(h) ? null : p) // null: ambiguous (several files with that content)
    }
    const renamed = []
    const matched = new Set()
    for (const p of onlyNewer) {
      const from = byHash.get(newer.files.get(p))
      if (from && !matched.has(from)) {
        renamed.push({ older: from, newer: p })
        matched.add(from)
      }
    }
    for (const m of manual.filter((x) => x.from === older.id && x.to === newer.id)) {
      if (!renamed.some((r) => r.newer === m.newer)) {
        renamed.push({ older: m.older, newer: m.newer })
        matched.add(m.older)
      }
    }
    const renamedNewer = new Set(renamed.map((r) => r.newer))
    transitions.push({
      from: older.id,
      to: newer.id,
      renamed: renamed.sort((a, b) => a.newer.localeCompare(b.newer)),
      added: onlyNewer.filter((p) => !renamedNewer.has(p)).sort(),
      removed: onlyOlder.filter((p) => !matched.has(p)).sort()
    })
  }
  return {
    schemaVersion: 1,
    description:
      'Texture path changes between consecutive Minecraft versions (generated by scripts/gen-migrations.mjs from the misode/mcmeta asset trees; "manual" holds hand-reviewed renames). Paths only, no game files.',
    generatedAt,
    versions: trees.map((t) => t.id),
    manual,
    transitions
  }
}

/** git blob hash of a file content (what GitHub trees report). */
export function gitBlobSha(bytes) {
  return createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex')
}

async function fetchTree(id) {
  const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN
  const url = `https://api.github.com/repos/misode/mcmeta/git/trees/${encodeURIComponent(`${id}-assets`)}?recursive=1`
  const response = await fetch(url, {
    headers: {
      Accept: 'application/vnd.github+json',
      'User-Agent': 'blocksmith-studio-gen-migrations',
      ...(token ? { Authorization: `Bearer ${token}` } : {})
    }
  })
  if (!response.ok) throw new Error(`HTTP ${response.status} for ${url}`)
  const body = await response.json()
  if (body.truncated) throw new Error(`Tree of ${id} is truncated`)
  const files = new Map()
  for (const entry of body.tree) {
    if (entry.type === 'blob' && TEXTURE.test(entry.path)) files.set(entry.path, entry.sha)
  }
  return { id, files }
}

/** Compares one texture of a local client jar (if any) with the tree. */
function crossCheck(tree) {
  const mc =
    process.platform === 'darwin'
      ? join(homedir(), 'Library/Application Support/minecraft')
      : process.platform === 'win32'
        ? join(process.env.APPDATA ?? '', '.minecraft')
        : join(homedir(), '.minecraft')
  const jar = join(mc, 'versions', tree.id, `${tree.id}.jar`)
  if (!existsSync(jar)) return false
  const path = 'assets/minecraft/textures/block/stone.png'
  const files = unzipSync(readFileSync(jar), { filter: (f) => f.name === path })
  const sha = files[path] ? gitBlobSha(files[path]) : undefined
  if (sha !== tree.files.get(path)) {
    throw new Error(`Cross-check failed for ${tree.id}: jar ${sha}, tree ${tree.files.get(path)}`)
  }
  console.log(`Cross-check OK: ${tree.id} (local jar)`)
  return true
}

async function main() {
  const args = new Set(process.argv.slice(2))
  const table = JSON.parse(readFileSync(VERSIONS, 'utf8'))
  const ordered = [...table.versions].sort(
    (a, b) => Date.parse(a.releaseTime) - Date.parse(b.releaseTime)
  )
  const first = ordered.findIndex((v) => v.id === FIRST_VERSION)
  if (first < 0) throw new Error(`${FIRST_VERSION} is not in versions.json`)
  const ids = ordered.slice(first).map((v) => v.id)
  const previous = existsSync(OUTPUT) ? JSON.parse(readFileSync(OUTPUT, 'utf8')) : { manual: [] }
  const trees = []
  for (const id of ids) {
    const tree = await fetchTree(id)
    console.log(`${id}: ${tree.files.size} textures`)
    crossCheck(tree)
    trees.push(tree)
  }
  const migrations = buildMigrations(
    trees,
    previous.manual ?? [],
    new Date().toISOString().slice(0, 10)
  )
  for (const t of migrations.transitions) {
    console.log(
      `${t.from} -> ${t.to}: ${t.renamed.length} renamed, ${t.added.length} added, ${t.removed.length} removed`
    )
  }
  if (args.has('--dry-run')) return
  await writeFile(OUTPUT, JSON.stringify(migrations, null, 2) + '\n')
  console.log(`Wrote ${OUTPUT}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((err) => {
    console.error(err instanceof Error ? err.message : err)
    process.exit(1)
  })
}
