import { promises as fs } from 'node:fs'
import { join } from 'node:path'
import {
  StyleBriefSchema,
  emptyBrief,
  type StyleBrief,
  type StyleBriefPatch
} from '@shared/model/brief'
import { AppErrorException } from '../ipc/registry'
import { writeFileAtomic } from './packs/files'
import { META_DIR } from './packs/project'

/** Per-pack shared agent memory (PLAN 6.5). */
export const BRIEF_FILE = `${META_DIR}/style-brief.json`
/** requestLog keeps the most recent entries only. */
export const REQUEST_LOG_MAX = 30
export const DECISIONS_MAX = 100
const TEXT_MAX = 300

export type BriefAuthor = StyleBrief['decisions'][number]['by']
export type BriefAgent = StyleBrief['requestLog'][number]['agent']

function clip(text: string, max = TEXT_MAX): string {
  const t = text.trim()
  return t.length <= max ? t : `${t.slice(0, max - 3)}...`
}

/** Pure: applies a patch (theme, palette and rules replace; addDecision appends a decision by `by`). */
export function applyBriefPatch(
  brief: StyleBrief,
  patch: StyleBriefPatch,
  by: BriefAuthor,
  at: string
): StyleBrief {
  const next: StyleBrief = {
    ...brief,
    ...(patch.theme !== undefined ? { theme: patch.theme } : {}),
    ...(patch.palette !== undefined ? { palette: patch.palette.map((p) => ({ ...p })) } : {}),
    ...(patch.rules !== undefined ? { rules: [...patch.rules] } : {}),
    decisions: brief.decisions
  }
  if (patch.addDecision?.trim()) {
    next.decisions = [...brief.decisions, { at, by, text: clip(patch.addDecision) }].slice(
      -DECISIONS_MAX
    )
  }
  return next
}

/** Pure: appends a decision line (kept to the last DECISIONS_MAX). */
export function addDecision(
  brief: StyleBrief,
  text: string,
  by: BriefAuthor,
  at: string
): StyleBrief {
  return {
    ...brief,
    decisions: [...brief.decisions, { at, by, text: clip(text) }].slice(-DECISIONS_MAX)
  }
}

/** Pure: appends a request summary (kept to the last REQUEST_LOG_MAX). */
export function appendRequestLog(
  brief: StyleBrief,
  agent: BriefAgent,
  summary: string,
  at: string
): StyleBrief {
  return {
    ...brief,
    requestLog: [...brief.requestLog, { at, agent, summary: clip(summary) }].slice(-REQUEST_LOG_MAX)
  }
}

export interface BriefServiceDeps {
  locate: (packId: string) => Promise<{ folder: string } | null>
  now?: () => Date
}

export interface BriefChange {
  /** Patches applied in order; their decisions are attributed to `by`. */
  patches?: StyleBriefPatch[]
  by: BriefAuthor
  /** Extra decision line by `by`. */
  decision?: string
  /** One-line summary of an applied proposal (generated by the app). */
  requestLog?: { agent: BriefAgent; summary: string }
}

export interface BriefService {
  /** The pack's brief; missing or invalid file -> empty brief (an invalid file is kept as .bak). */
  get(packId: string): Promise<StyleBrief>
  /** User edits (decisions by 'user') or an agent's accepted patch. */
  update(packId: string, patch: StyleBriefPatch, by?: BriefAuthor): Promise<StyleBrief>
  /** Several changes in one atomic write. */
  change(packId: string, change: BriefChange): Promise<StyleBrief>
}

export function createBriefService(deps: BriefServiceDeps): BriefService {
  const now = deps.now ?? ((): Date => new Date())
  const queues = new Map<string, Promise<unknown>>()

  /** Serializes reads and writes per pack so concurrent updates never lose a change. */
  function enqueue<T>(packId: string, fn: () => Promise<T>): Promise<T> {
    const prev = queues.get(packId) ?? Promise.resolve()
    const run = prev.then(fn, fn)
    const tail = run.catch(() => undefined)
    queues.set(packId, tail)
    void tail.then(() => {
      if (queues.get(packId) === tail) queues.delete(packId)
    })
    return run
  }

  async function fileOf(packId: string): Promise<string> {
    const location = await deps.locate(packId)
    if (!location) throw new AppErrorException('packs.notFound', { packId })
    return join(location.folder, ...BRIEF_FILE.split('/'))
  }

  async function read(file: string): Promise<StyleBrief> {
    let raw: string
    try {
      raw = await fs.readFile(file, 'utf8')
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return emptyBrief()
      throw err
    }
    try {
      const parsed = StyleBriefSchema.safeParse(JSON.parse(raw))
      if (parsed.success) return parsed.data
    } catch {
      // invalid JSON: handled below
    }
    await fs.copyFile(file, `${file}.bak`).catch(() => undefined)
    return emptyBrief()
  }

  async function write(file: string, brief: StyleBrief): Promise<StyleBrief> {
    const valid = StyleBriefSchema.parse({ ...brief, updatedAt: now().toISOString() })
    await writeFileAtomic(file, `${JSON.stringify(valid, null, 2)}\n`)
    return valid
  }

  function change(packId: string, c: BriefChange): Promise<StyleBrief> {
    return enqueue(packId, async () => {
      const file = await fileOf(packId)
      const at = now().toISOString()
      let brief = await read(file)
      for (const patch of c.patches ?? []) brief = applyBriefPatch(brief, patch, c.by, at)
      if (c.decision?.trim()) brief = addDecision(brief, c.decision, c.by, at)
      if (c.requestLog)
        brief = appendRequestLog(brief, c.requestLog.agent, c.requestLog.summary, at)
      return write(file, brief)
    })
  }

  return {
    get: (packId) => enqueue(packId, async () => read(await fileOf(packId))),
    update: (packId, patch, by = 'user') => change(packId, { patches: [patch], by }),
    change
  }
}
